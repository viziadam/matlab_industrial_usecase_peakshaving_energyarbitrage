function evalCfg = create_evaluation_config(cfg)
% CREATE_EVALUATION_CONFIG
%
% Kiértékelési konfiguráció egy adott futáshoz.
% A bemeneti eredményfájl neve automatikusan a topológia és a működési mód
% alapján képződik:
%   results_dc_peak_only.mat
%   results_dc_energy_only.mat
%   results_dc_combined.mat
%   results_ac_peak_only.mat
%   results_ac_energy_only.mat
%   results_ac_combined.mat

    if ~isfield(cfg, 'paths')
        error('cfg.paths hianyzik.');
    end

    if ~isfield(cfg.paths, 'results')
        error('cfg.paths.results hianyzik.');
    end

    if ~isfield(cfg.paths, 'figures')
        error('cfg.paths.figures hianyzik.');
    end

    if ~isfield(cfg, 'system') || ~isfield(cfg.system, 'bessCoupling')
        error('cfg.system.bessCoupling hianyzik.');
    end

    if ~isfield(cfg, 'dispatch') || ~isfield(cfg.dispatch, 'objectiveMode')
        error('cfg.dispatch.objectiveMode hianyzik.');
    end

    if ~isfield(cfg, 'cost')
        error('cfg.cost hianyzik.');
    end

    requiredCostFields = { ...
        'pv_huf_per_kWp', ...
        'bess_huf_per_kWh', ...
        'bess_power_huf_per_kW', ...
        'inverter_huf_per_kW', ...
        'grid_import_huf_per_kWh', ...
        'pv_opex_frac_per_year', ...
        'bess_opex_frac_per_year', ...
        'inverter_opex_frac_per_year'};

    for i = 1:numel(requiredCostFields)
        f = requiredCostFields{i};
        if ~isfield(cfg.cost, f)
            error('cfg.cost.%s hianyzik.', f);
        end
    end

    coupling = lower(string(cfg.system.bessCoupling));
    objectiveMode = lower(string(cfg.dispatch.objectiveMode));

    if ~(coupling == "dc" || coupling == "ac")
        error('Invalid cfg.system.bessCoupling: %s', coupling);
    end

    if ~(objectiveMode == "peak_only" || objectiveMode == "energy_only" || objectiveMode == "combined")
        error('Invalid cfg.dispatch.objectiveMode: %s', objectiveMode);
    end

    resultFileName = sprintf('results_%s_%s.mat', coupling, objectiveMode);

    evalCfg = struct();
    evalCfg.input = struct();
    evalCfg.output = struct();
    evalCfg.plots = struct();
    evalCfg.selection = struct();
    evalCfg.report = struct();
    evalCfg.economics = struct();

    % ---------------------------------------------------------------------
    % Input / output
    % ---------------------------------------------------------------------
    evalCfg.input.resultFilePath = fullfile(cfg.paths.results, resultFileName);

    evalCfg.output.baseFolder = fullfile( ...
        cfg.paths.results, ...
        sprintf('evaluation_%s_%s', coupling, objectiveMode));

    if ~isfolder(evalCfg.output.baseFolder)
        mkdir(evalCfg.output.baseFolder);
    end

    evalCfg.output.saveEvaluationMat = true;
    evalCfg.output.saveEvaluationCsv = false;
    evalCfg.output.saveReportTables = true;

    % ---------------------------------------------------------------------
    % Plot beallitasok
    % ---------------------------------------------------------------------
    evalCfg.plots.makePlots = true;
    evalCfg.plots.makeCandidateSweepPlots = true;
    evalCfg.plots.makeSelectedCandidateYearlyPlots = false;

    % ---------------------------------------------------------------------
    % Kivalasztasi logika
    % ---------------------------------------------------------------------
    evalCfg.selection.mode = "minTotalLifecycleCost";
    evalCfg.selection.minGridImportReduction_pct = 0;
    evalCfg.selection.requirePositiveNPV = false;
    evalCfg.selection.requireBESS = false;

    % ---------------------------------------------------------------------
    % Riport kategoriak
    % ---------------------------------------------------------------------
    evalCfg.report.smallBessMaxRatio = 1.0;
    evalCfg.report.largeBessMinRatio = 2.0;

    evalCfg.report.matrixMetrics = struct( ...
        'field', { ...
            'LCSE_HUF_per_kWh_saved', ...
            'NPV_millionHUF', ...
            'selfSufficiency_pct' ...
        }, ...
        'label', { ...
            'LCSE - megtakaritott energia fajlagos koltsege', ...
            'Netto jelenertek', ...
            'Onellatasi arany' ...
        }, ...
        'unit', { ...
            'Ft/kWh', ...
            'millio Ft', ...
            '%' ...
        }, ...
        'direction', { ...
            'min', ...
            'max', ...
            'max' ...
        }, ...
        'fileTag', { ...
            'lcse', ...
            'npv', ...
            'self_sufficiency' ...
        });

    evalCfg.metrics = struct( ...
        'field', { ...
            'totalLifecycleCost_HUF', ...
            'NPV_HUF', ...
            'objectiveCost_HUF', ...
            'energyCost_HUF', ...
            'contractCost_HUF', ...
            'overrunCost_HUF', ...
            'degradationCost_HUF', ...
            'bestContract_kW', ...
            'peakReduction_pct', ...
            'equivalentCycles' ...
        }, ...
        'label', { ...
            'Teljes eletciklus koltseg', ...
            'Netto jelenertek', ...
            'Szimulalt idoszak operativ koltsege', ...
            'Energiakoltseg', ...
            'Lekotott teljesitmeny koltsege', ...
            'Tullepesi koltseg', ...
            'Degradacios koltseg', ...
            'Optimalis lekotott teljesitmeny', ...
            'Peak reduction', ...
            'Ekvivalens ciklusszam' ...
        }, ...
        'unit', { ...
            'HUF', ...
            'HUF', ...
            'HUF', ...
            'HUF', ...
            'HUF', ...
            'HUF', ...
            'HUF', ...
            'kW', ...
            '%', ...
            '-' ...
        }, ...
        'direction', { ...
            'min', ...
            'max', ...
            'min', ...
            'min', ...
            'min', ...
            'min', ...
            'min', ...
            'min', ...
            'max', ...
            'min' ...
        });

    % ---------------------------------------------------------------------
    % Gazdasagi feltetelezesek
    % ---------------------------------------------------------------------
    evalCfg.economics.simYears = cfg.analysis.simYears;
    evalCfg.economics.projectLifetime_years = cfg.cost.project_lifetime_years;
    evalCfg.economics.pvLifetime_years = cfg.cost.pv_lifetime_years;
    evalCfg.economics.inverterLifetime_years = cfg.cost.inverter_lifetime_years;
    evalCfg.economics.discountRate = cfg.cost.discount_rate;

    evalCfg.economics.pv_opex_frac_per_year = cfg.cost.pv_opex_frac_per_year;
    evalCfg.economics.bess_opex_frac_per_year = cfg.cost.bess_opex_frac_per_year;
    evalCfg.economics.inverter_opex_frac_per_year = cfg.cost.inverter_opex_frac_per_year;
end
