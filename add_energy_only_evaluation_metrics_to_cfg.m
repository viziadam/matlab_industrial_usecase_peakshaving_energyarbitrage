function cfg = add_energy_only_evaluation_metrics_to_cfg(cfg)
% ADD_ENERGY_ONLY_EVALUATION_METRICS_TO_CFG
%
% Kiterjeszti a cfg.output.scalarMetrics listat azokkal az energiaaramlasi
% es veszteseg metrikakkal, amelyek az energy_only es combined dolgozati
% kiertekeleshez kellenek.
%
% A fuggveny idempotens: ha egy metrika mar szerepel a listaban, nem adja
% hozza ujra.

    if ~isfield(cfg, 'output') || ~isfield(cfg.output, 'scalarMetrics')
        error('Missing cfg.output.scalarMetrics.');
    end

    extraMetrics = struct( ...
        'name', { ...
            'pvToLoad_kWh', ...
            'gridToLoad_kWh', ...
            'bessToLoad_kWh', ...
            'pvToBess_kWh', ...
            'gridToBess_kWh', ...
            'inverterLoss_kWh', ...
            'centralInverterLoss_kWh', ...
            'pcsbInverterLoss_kWh', ...
            'dcdcLoss_kWh', ...
            'bessInternalLoss_kWh', ...
            'clippedEnergy_kWh', ...
            'gridToBessDc_kWh', ...
            'gridToBessAc_kWh', ...
            'pvToBessDc_kWh', ...
            'pvToBessAc_kWh', ...
            'bessDcToLoad_kWh', ...
            'bessAcToLoad_kWh', ...
            'bessChargeDc_kWh', ...
            'bessChargeAc_kWh', ...
            'bessDischargeDc_kWh', ...
            'bessDischargeAc_kWh', ...
            'bessInternalLossDc_kWh', ...
            'bessInternalLossAc_kWh' ...
        }, ...
        'source', { ...
            'P_pv_to_load_kW', ...
            'P_grid_to_load_kW', ...
            'P_bess_to_load_kW', ...
            'P_pv_to_bess_kW', ...
            'P_grid_to_bess_kW', ...
            'P_loss_inv_kW', ...
            'P_loss_central_inv_kW', ...
            'P_loss_pcsb_inv_kW', ...
            'P_loss_dcdc_kW', ...
            'P_loss_bess_internal_kW', ...
            'P_curtailment_kW', ...
            'P_grid_to_bess_dc_kW', ...
            'P_grid_to_bess_ac_kW', ...
            'P_pv_to_bess_dc_kW', ...
            'P_pv_to_bess_ac_kW', ...
            'P_bess_dc_to_load_kW', ...
            'P_bess_ac_to_load_kW', ...
            'P_bess_charge_dc_kW', ...
            'P_bess_charge_ac_kW', ...
            'P_bess_discharge_dc_kW', ...
            'P_bess_discharge_ac_kW', ...
            'P_loss_bess_internal_dc_kW', ...
            'P_loss_bess_internal_ac_kW' ...
        }, ...
        'mode', { ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum', ...
            'energySum' ...
        });

    existingNames = string({cfg.output.scalarMetrics.name});

    for k = 1:numel(extraMetrics)
        if ~any(existingNames == string(extraMetrics(k).name))
            cfg.output.scalarMetrics(end+1) = extraMetrics(k); %#ok<AGROW>
            existingNames(end+1) = string(extraMetrics(k).name); %#ok<AGROW>
        end
    end
end
